create extension if not exists pgcrypto;

alter table public.orders
  add column if not exists payment_provider text,
  add column if not exists payment_invoice_id text,
  add column if not exists payment_page_url text,
  add column if not exists payment_amount_minor bigint,
  add column if not exists payment_currency integer,
  add column if not exists payment_created_at timestamptz,
  add column if not exists payment_modified_at timestamptz,
  add column if not exists paid_at timestamptz,
  add column if not exists payment_failure_reason text,
  add column if not exists payment_error_code text,
  add column if not exists payment_return_token_hash text;

create unique index if not exists orders_payment_invoice_id_uidx
  on public.orders(payment_invoice_id)
  where payment_invoice_id is not null;

create table if not exists public.payment_settings (
  id text primary key,
  enabled boolean not null default false,
  provider text not null default 'monobank',
  invoice_validity_seconds integer not null default 3600 check (invoice_validity_seconds between 300 and 2592000),
  test_mode boolean not null default false,
  updated_at timestamptz not null default now()
);

insert into public.payment_settings (id, enabled, provider, invoice_validity_seconds, test_mode)
values ('card_online', false, 'monobank', 3600, false)
on conflict (id) do nothing;

create table if not exists public.payment_attempts (
  id uuid primary key default gen_random_uuid(),
  order_id bigint not null references public.orders(id) on delete cascade,
  provider text not null default 'monobank',
  invoice_id text not null unique,
  page_url text,
  reference text not null,
  amount_minor bigint not null check (amount_minor > 0),
  currency integer not null default 980,
  status text not null default 'created',
  provider_created_at timestamptz,
  provider_modified_at timestamptz,
  paid_at timestamptz,
  failure_reason text,
  error_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists payment_attempts_order_id_idx
  on public.payment_attempts(order_id, created_at desc);

create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  payment_attempt_id uuid references public.payment_attempts(id) on delete cascade,
  order_id bigint references public.orders(id) on delete cascade,
  provider text not null default 'monobank',
  invoice_id text not null,
  provider_status text not null,
  provider_modified_at timestamptz not null,
  amount_minor bigint,
  currency integer,
  accepted boolean not null default false,
  reason text,
  payload jsonb,
  created_at timestamptz not null default now(),
  unique (invoice_id, provider_status, provider_modified_at)
);

alter table public.payment_settings enable row level security;
alter table public.payment_attempts enable row level security;
alter table public.payment_events enable row level security;

